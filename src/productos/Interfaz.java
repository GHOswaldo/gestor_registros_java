    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = tablilla.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(null, "No se ha seleccionado ninguna fila.");
            return;
        }

        int id = Integer.parseInt(this.tablilla.getValueAt(fila, 0).toString());
        try {
            PreparedStatement ps = obj.con.prepareStatement("DELETE FROM " + nomtabla + " WHERE " + var1 + " = ?");
            ps.setInt(1, id);
            ps.executeUpdate();
            JOptionPane.showMessageDialog(null, "Registro eliminado.");

            titulosTab(t1, t2, t3, t4, t5);
            llenar(nomtabla, t1, t2, t3, t4, t5);

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Error al eliminar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        int fila = tablilla.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(null, "No se ha seleccionado ninguna fila.");
            return;
        }

        int id = Integer.parseInt(this.tablilla.getValueAt(fila, 0).toString());
        String alexander1 = tablilla.getValueAt(fila, 1).toString();
        String alexander2 = tablilla.getValueAt(fila, 2).toString();
        String alexamder3 = tablilla.getValueAt(fila, 3).toString();
        String alexander4 = tablilla.getValueAt(fila, 4).toString();

        try {
            PreparedStatement ps = obj.con.prepareStatement("UPDATE " + nomtabla + " SET " + var2 + "=?, " + var3 + "=?, " + var4 + "=?, " + var5 + "=? WHERE " + var1 + "=?");

            ps.setString(1, alexander1);
            ps.setString(2, alexander2);
            ps.setString(3, alexamder3);
            ps.setString(4, alexander4);
            ps.setInt(5, id);

            int filas = ps.executeUpdate();
            llenar(nomtabla, t1, t2, t3, t4, t5);

            if (filas > 0) {
                JOptionPane.showMessageDialog(null, "Registro actualizado con éxito.");
            } else {
                JOptionPane.showMessageDialog(null, "El registro no se pudo actualizar.");
            }

            titulosTab(t1, t2, t3, t4, t5);

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Error al actualizar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnModificarActionPerformed

