    public void llenar(String nomT, String ti1, String ti2, String ti3, String ti4, String ti5) {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn(ti1);
        model.addColumn(ti2);
        model.addColumn(ti3);
        model.addColumn(ti4);
        model.addColumn(ti5);
        try {
            String buscar = "Select * from " + nomT;
            Statement stm = obj.con.createStatement();
            ResultSet rs = stm.executeQuery(buscar);
            while (rs.next()) {
                Object[] fila = new Object[5];
                for (int i = 0; i < 5; i++) {
                    fila[i] = rs.getObject(i + 1);
                }
                model.addRow(fila);
            }
        } catch (SQLException error) {
            System.out.println("Error: " + error);
        }
        tablilla.setModel(model);
    }

