    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        String agregar = "INSERT INTO " + nomtabla + " (" + var1 + ", " + var2 + ", " + var3 + ", " + var4 + ", " + var5 + ") VALUES  (?,?,?,?,?)";
        try {
            PreparedStatement pst = obj.con.prepareStatement(agregar);
            for (int i = 0; i < tablilla.getRowCount(); i++) {
                String c1 = (String) tablilla.getValueAt(i, 0);
                String c2 = (String) tablilla.getValueAt(i, 1);
                String c3 = (String) tablilla.getValueAt(i, 2);
                String c4 = (String) tablilla.getValueAt(i, 3);
                String c5 = (String) tablilla.getValueAt(i, 4);

                pst.setString(1, c1);
                pst.setString(2, c2);
                pst.setString(3, c3);
                pst.setString(4, c4);
                pst.setString(5, c5);

                pst.executeUpdate();

            }
            JOptionPane.showMessageDialog(null, "Registro(s) agregado(s) con éxito.");

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "Error al agregar los registros.");
        }
        titulosTab(t1, t2, t3, t4, t5);
    }//GEN-LAST:event_btnAgregarActionPerformed

